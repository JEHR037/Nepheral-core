let LANG = localStorage.getItem('nepheral_lang')
  || ((navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en');

// The phone app: mobile.html, and the shared account screens opened with ?m=1.
const MOBILE = /[?&]m=1(?:&|$)/.test(location.search) || /mobile\.html$/.test(location.pathname);

function t(key, vars) {
  const ph = MOBILE && typeof PH !== 'undefined' ? (PH[LANG][key] ?? PH.en[key]) : undefined;
  let s = ph ?? I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (Array.isArray(s)) return s;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', v);
  return s;
}

function setLang(lang) {
  LANG = lang;
  localStorage.setItem('nepheral_lang', lang);
  location.reload();
}

/// Map raw backend/command errors to friendly localized messages.
function friendlyError(raw) {
  const s = String(raw);
  if (s.includes('not included in a block')) return t('err.notIncluded');
  if (s.toLowerCase().includes('insufficient balance')) return t('err.balance');
  if (s.includes('Invalid mnemonic')) return t('err.mnemonic');
  if (s.includes('Bad room code') || s.includes('room code')) return t('err.roomCode');
  if (s.includes('Invalid address') || s === 'bad addr') return t('err.addr');
  if (s.includes('64 hex')) return t('err.recipient');
  if (s.includes('amount must be')) return t('err.amount');
  if (s.includes('session gone') || s.includes('room gone')) return t('err.sessionGone');
  if (s.includes('--features cpu')) return t('err.hwNeedsCpu');
  if (s.includes('is already installed')) return t('err.modelAlreadyInstalled');
  if (s.includes('download is already in progress')) return t('err.modelDownloadBusy');
  return t('err.generic', { detail: s });
}
